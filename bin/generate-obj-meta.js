#!/usr/bin/env node
// generate-obj-meta writes an OBJ model's meta file, a JSON file beside it
// with the same name, such as rock-boulder.meta.json for rock-boulder.obj
// (see "Model meta files" in the README, and bin/lib/meta.js, which other
// formats' scripts share).
//
// A meta file holds two kinds of things:
// - What only the model's generator knows, such as the parameters it was
//   made with, its colliders or a tree's skeleton. The generators in bin/
//   call writeMeta with them every time they write a model.
// - What it works out from the model itself: its bounds, the corners of the
//   box around it, {"min": [x, y, z], "max": [x, y, z]}, how many vertices
//   and triangles it has, and the model's hash, modelHash, which tells
//   whether the model changed after its meta file was written.
//
// Run on its own, it writes the meta files of the OBJ files it is given. For
// each one, it measures the file again and records its hash, and keeps every
// other field already in the meta file, such as a generator's colliders. So
// for a model no generator made, it writes everything there is to know. For
// a generated model whose file changed, rerun its generator instead: this
// script would record the new hash but keep the old colliders, hiding that
// they no longer match the model.
//
// With --check, it writes nothing. It lists the models whose meta file is
// missing, or whose modelHash doesn't match the model file any more, and
// exits with 1 if there are any:
//
//   node bin/generate-obj-meta.js airboat.obj cube.obj
//   node bin/generate-obj-meta.js --all
//   node bin/generate-obj-meta.js --check --all
//
// Files are found in resources/obj unless their path says otherwise. --all
// does every OBJ file there, other than a model's parts, such as a tree's
// bark, whose header names its model's meta file rather than its own.

const fs = require("fs");
const path = require("path");

const {checkMeta, metaFileOf, readMeta, writeMetaFile} = require("./lib/meta.js");

const objFolder = path.join(__dirname, "..", "resources", "obj");

// metaHeader returns the comment lines a generator puts at the top of the
// OBJ file at output, through Mesh's toObj: "Generated by" meta's generator,
// and "Meta in" the name of output's meta file. They are only for people
// reading the file; nothing loads the meta file through them. A model's
// parts, such as a tree's bark, get the same lines, naming the model's meta
// file.
function metaHeader(output, meta) {
  return [`Generated by ${meta.generator}`, `Meta in ${path.basename(metaFileOf(output))}`];
}

// measure reads the OBJ file at file and returns its bounds, {min, max},
// the corners of the box around its vertices, and how many vertices and
// triangles it has, counting a polygon of n sides as n - 2 triangles.
function measure(file) {
  const min = [Infinity, Infinity, Infinity];
  const max = [-Infinity, -Infinity, -Infinity];
  let vertices = 0;
  let triangles = 0;
  for (const line of fs.readFileSync(file, "utf8").split("\n")) {
    const [kind, ...values] = line.trim().split(/\s+/);
    if (kind === "v") {
      vertices++;
      for (let axis = 0; axis < 3; axis++) {
        min[axis] = Math.min(min[axis], Number(values[axis]));
        max[axis] = Math.max(max[axis], Number(values[axis]));
      }
    } else if (kind === "f") {
      triangles += values.length - 2;
    }
  }
  return {bounds: {min, max}, vertices, triangles};
}

// writeMeta writes the meta file of the OBJ file at output, which must
// already be written: the fields of meta, what its generator knows about
// it, then what measure returns, then the file's hash (see writeMetaFile).
function writeMeta(output, meta) {
  writeMetaFile(output, meta, measure(output));
}

// isPart returns whether the OBJ file at file is part of another model,
// such as a tree's bark: its "Meta in" header line names another model's
// meta file.
function isPart(file) {
  const [, metaFile] = fs.readFileSync(file, "utf8").match(/^# Meta in (\S+)$/m) ?? [];
  return !!metaFile && metaFile !== path.basename(metaFileOf(file));
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const names = args.filter((arg) => !arg.startsWith("--"));
  const files = args.includes("--all")
    ? fs
        .readdirSync(objFolder)
        .filter((name) => name.endsWith(".obj"))
        .map((name) => path.join(objFolder, name))
        .filter((file) => !isPart(file))
    : names.map((file) => (path.isAbsolute(file) ? file : path.join(objFolder, file)));
  if (!files.length) {
    throw new Error("name the OBJ files to write meta files for, such as cube.obj, or --all");
  }
  /* eslint-disable no-console */
  if (check) {
    const problems = files.map((file) => [file, checkMeta(file)]).filter(([, problem]) => problem);
    for (const [file, problem] of problems) {
      console.log(`${path.relative(process.cwd(), file)}: ${problem}`);
    }
    process.exitCode = problems.length ? 1 : 0;
    return;
  }
  for (const file of files) {
    writeMeta(file, readMeta(file));
    console.log(`wrote ${metaFileOf(file)}`);
  }
  /* eslint-enable no-console */
}

if (require.main === module) {
  main();
}

module.exports = {metaHeader, writeMeta};
