#!/usr/bin/env node
// generate-gate writes a bubbly race gate as an OBJ file: a ring of round
// bubbles, like a balloon arch, for racers to fly through. Bubbles take turns
// with the palette's colors and alternate between big and small, and each has
// a cartoon highlight on its upper side. Everything is colored with vertex
// colors, so it renders without a material color: the lit shaders add the
// material color to the vertex color, so leave it black, or use it to make a
// gate glow, as a race does to show which gate is next (see
// apps/editor/scripts/race.js).
//
// The ring stands in the XY plane around the origin, so racers fly through
// it along Z, and its radius is the radius of the circle through the
// bubbles' centers.
//
// Usage:
//   node bin/generate-gate.js                      race-gate.obj
//   node bin/generate-gate.js --palette checker    race-gate-checker.obj, for a start gate
//   node bin/generate-gate.js --radius 400 --bubbles 30 --out big-gate.obj
//
// Parameters:
//   --palette: the bubbles' colors, one of candy, checker, mint or berry.
//     candy by default.
//   --radius: the ring's radius. 300 by default.
//   --bubbles: how many bubbles go around it. 20 by default.
//   --size: how big the big bubbles are, as a part of the space between
//     their centers. Over 0.5 they overlap. 0.62 by default.
//   --small: how big the small bubbles are, as a part of the big ones. 0.8 by
//     default.
//   --highlight: how much lighter each bubble's highlight is, 0 for none.
//     0.3 by default.

const fs = require("fs");
const path = require("path");

const {Mesh, add, dot, normalize, parseArgs} = require("./lib/mesh.js");

const defaults = {radius: 300, bubbles: 20, size: 0.62, small: 0.8, highlight: 0.3};

// Each palette's colors go around the ring in turn.
const palettes = {
  candy: [
    [1, 0.42, 0.5],
    [1, 0.93, 0.82],
  ],
  checker: [
    [0.12, 0.12, 0.16],
    [0.96, 0.96, 0.96],
  ],
  mint: [
    [0.35, 0.85, 0.7],
    [0.92, 1, 0.95],
  ],
  berry: [
    [0.6, 0.35, 0.95],
    [1, 0.75, 0.9],
  ],
};

// Resolution of a bubble.
const SIDES = 24;
const RINGS = 14;

// The way highlights face: up, and a little to the left and front, the way
// cartoons are usually lit.
const HIGHLIGHT = normalize([-0.45, 0.8, 0.4]);

function bubble(mesh, center, radius, color, highlight) {
  const lit = color.map((v) => v + (1 - v) * highlight);
  const rings = Array.from({length: RINGS + 1}, (_, i) => {
    const latitude = Math.PI * (i / RINGS - 0.5);
    return Array.from({length: SIDES}, (_, s) => {
      const longitude = (s / SIDES) * 2 * Math.PI;
      const normal = [
        Math.cos(latitude) * Math.cos(longitude),
        Math.sin(latitude),
        Math.cos(latitude) * Math.sin(longitude),
      ];
      const position = add(
        center,
        normal.map((v) => v * radius)
      );
      const shaded = highlight > 0 && dot(normal, HIGHLIGHT) > 0.65 ? lit : color;
      return mesh.vertex(position, normal, shaded);
    });
  });

  for (let i = 0; i < RINGS; i++) {
    for (let s = 0; s < SIDES; s++) {
      const t = (s + 1) % SIDES;
      mesh.quad(rings[i][s], rings[i][t], rings[i + 1][t], rings[i + 1][s]);
    }
  }
}

function buildGate({radius, bubbles, size, small, highlight}, colors) {
  const mesh = new Mesh();
  const spacing = (2 * Math.PI * radius) / bubbles;
  for (let i = 0; i < bubbles; i++) {
    const angle = (i / bubbles) * 2 * Math.PI;
    const center = [radius * Math.cos(angle), radius * Math.sin(angle), 0];
    const bubbleRadius = spacing * size * (i % 2 ? small : 1);
    bubble(mesh, center, bubbleRadius, colors[i % colors.length], highlight);
  }
  return mesh;
}

function main() {
  const {out, palette = "candy", ...overrides} = parseArgs(process.argv.slice(2));
  if (!palettes[palette]) {
    throw new Error(
      `unknown palette "${palette}"; palettes are ${Object.keys(palettes).join(", ")}`
    );
  }

  const parameters = {...defaults};
  for (const [name, value] of Object.entries(overrides)) {
    if (!(name in defaults)) {
      throw new Error(
        `unknown parameter "--${name}"; parameters are palette, ` + Object.keys(defaults).join(", ")
      );
    }
    parameters[name] = Number(value);
  }
  parameters.bubbles = Math.max(3, Math.round(parameters.bubbles));

  const filename = out || (palette === "candy" ? "race-gate.obj" : `race-gate-${palette}.obj`);
  const output = path.isAbsolute(filename)
    ? filename
    : path.join(__dirname, "..", "resources", "obj", filename);

  const mesh = buildGate(parameters, palettes[palette]);
  fs.writeFileSync(
    output,
    mesh.toObj(
      [
        "Generated by bin/generate-gate.js",
        `Parameters ${JSON.stringify({...parameters, palette})}`,
      ],
      "gate"
    )
  );

  // eslint-disable-next-line no-console
  console.log(
    `wrote ${output}: ${mesh.vertices.length} vertices, ${mesh.triangles.length} triangles`
  );
}

main();
